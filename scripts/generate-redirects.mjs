#!/usr/bin/env node
/**
 * Generate slug-change 301 redirects from CMS content.
 *
 * Reads pages/products/stories, finds each item's `previousSlugs` array, and
 * writes 301 redirects to public/_redirects between BEGIN/END auto-managed
 * markers.  Run automatically before `next build`.
 *
 * Idempotent — safe to run repeatedly. Manual entries above the markers are
 * preserved.
 */
import fs from 'node:fs'
import path from 'node:path'
import yaml from 'js-yaml'
import matter from 'gray-matter'

const ROOT = process.cwd()
const REDIRECTS_FILE = path.join(ROOT, 'public', '_redirects')
const BEGIN = '# === BEGIN AUTO-GENERATED CMS REDIRECTS ==='
const END = '# === END AUTO-GENERATED CMS REDIRECTS ==='

function readYamlCollection(collection) {
  const dir = path.join(ROOT, 'content', collection)
  if (!fs.existsSync(dir)) return []
  const items = []
  for (const slug of fs.readdirSync(dir)) {
    const file = path.join(dir, slug, 'index.yaml')
    if (!fs.existsSync(file)) continue
    try {
      const data = yaml.load(fs.readFileSync(file, 'utf-8')) || {}
      items.push({ slug, data })
    } catch (err) {
      console.warn(`[redirects] skipping ${file}:`, err.message)
    }
  }
  return items
}

function readStories() {
  const dir = path.join(ROOT, 'content', 'blog')
  if (!fs.existsSync(dir)) return []
  const items = []
  for (const locale of fs.readdirSync(dir)) {
    const localeDir = path.join(dir, locale)
    if (!fs.statSync(localeDir).isDirectory()) continue
    for (const file of fs.readdirSync(localeDir)) {
      if (!file.endsWith('.mdx') && !file.endsWith('.md')) continue
      const full = path.join(localeDir, file)
      try {
        const parsed = matter(fs.readFileSync(full, 'utf-8'))
        const slug = file.replace(/\.(mdx|md)$/, '')
        items.push({ slug, locale, data: parsed.data })
      } catch (err) {
        console.warn(`[redirects] skipping ${full}:`, err.message)
      }
    }
  }
  return items
}

function buildRedirects() {
  const lines = []
  lines.push('# Auto-generated by scripts/generate-redirects.mjs')
  lines.push('# Source: previousSlugs[] field on each CMS item')
  lines.push('# DO NOT edit manually — change `previousSlugs` in the admin instead.')
  lines.push('')

  const pages = readYamlCollection('pages')
  for (const p of pages) {
    const previous = Array.isArray(p.data.previousSlugs) ? p.data.previousSlugs : []
    const locale = p.data.locale || 'ru'
    if ((p.data.status || 'draft') !== 'published') continue
    for (const old of previous) {
      if (!old || old === p.slug) continue
      lines.push(`/${locale}/${old}/  /${locale}/${p.slug}/  301`)
      lines.push(`/${locale}/${old}   /${locale}/${p.slug}/  301`)
    }
  }

  const products = readYamlCollection('products')
  for (const p of products) {
    const previous = Array.isArray(p.data.previousSlugs) ? p.data.previousSlugs : []
    if ((p.data.status || 'draft') !== 'published') continue
    for (const old of previous) {
      if (!old || old === p.slug) continue
      for (const locale of ['ru', 'uz']) {
        lines.push(`/${locale}/products/${old}/  /${locale}/products/${p.slug}/  301`)
        lines.push(`/${locale}/products/${old}   /${locale}/products/${p.slug}/  301`)
      }
    }
  }

  const stories = readStories()
  for (const s of stories) {
    const previous = Array.isArray(s.data.previousSlugs) ? s.data.previousSlugs : []
    for (const old of previous) {
      if (!old || old === s.slug) continue
      lines.push(`/${s.locale}/blog/${old}/  /${s.locale}/blog/${s.slug}/  301`)
      lines.push(`/${s.locale}/blog/${old}   /${s.locale}/blog/${s.slug}/  301`)
    }
  }

  return lines.join('\n')
}

function applyToFile(generated) {
  let current = ''
  if (fs.existsSync(REDIRECTS_FILE)) {
    current = fs.readFileSync(REDIRECTS_FILE, 'utf-8')
  }
  const block = `${BEGIN}\n${generated}\n${END}\n`
  let updated
  if (current.includes(BEGIN) && current.includes(END)) {
    updated = current.replace(
      new RegExp(`${BEGIN}[\\s\\S]*?${END}\\n?`),
      block
    )
  } else {
    updated = (current.trimEnd() + '\n\n' + block).replace(/\n{3,}/g, '\n\n')
  }
  if (updated === current) return false
  fs.writeFileSync(REDIRECTS_FILE, updated, 'utf-8')
  return true
}

const out = buildRedirects()
const wrote = applyToFile(out)
const ruleCount = out.split('\n').filter((l) => /^\/.+\s+\/.+\s+\d+/.test(l)).length
console.log(
  `[redirects] ${ruleCount} CMS redirect(s) ${wrote ? 'written to' : 'already up-to-date in'} public/_redirects`
)
